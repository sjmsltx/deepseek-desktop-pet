#: 每类展开的 5 个侧面（模板，保证 1200 条不重复）
ASPECTS = [
    ('具体', '用户提到{seed}的具体情况，涉及一些细节'),
    ('偏好', '用户对{seed}表现出明显的偏好'),
    ('变化', '用户关于{seed}的想法最近有了变化'),
    ('关联', '用户在{seed}这件事上和别人有过交流'),
    ('持续', '用户在{seed}上保持了较长时间的习惯'),
]


def gen_corpus():
    """240 种子 × 5 侧面 = 1200 条语料（不是记忆，是待抽取的对话素材）"""
    out = []
    for cat, seeds in SEEDS.items():
        for seed in seeds:
            for aspect, tpl in ASPECTS:
                out.append({
                    'id': 'c%04d' % (len(out) + 1),
                    'cat': cat,
                    'seed': seed,
                    'aspect': aspect,
                    'text': tpl.format(seed=seed),
                })
    return out


